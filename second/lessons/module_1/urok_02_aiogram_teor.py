import asyncio
import logging
from aiogram import Bot, Dispatcher, types, F
from aiogram.filters.command import Command

# 1. Логирование
logging.basicConfig(level=logging.INFO)

# 2. Тело и мозг
bot = Bot(token="ВСТАВЬ_СЮДА_СВОЙ_ТОКЕН")
dp = Dispatcher()


# 3. Ловушки (хэндлеры)

@dp.message(Command("start"))
async def cmd_start(message: types.Message):
    """Приветствие по команде /start"""
    await message.answer(f"Привет, {message.from_user.first_name}! Я готов к работе!")


@dp.message(F.text)
async def echo_mirror(message: types.Message):
    """Цифровое зеркало: повторяет текст пользователя"""
    await message.answer(message.text)


@dp.message(F.sticker)
async def sticker_handler(message: types.Message):
    """Ловушка для стикеров: возвращает стикер и его ID"""
    await message.answer_sticker(message.sticker.file_id)
    await message.answer(f"Я сохранил паспортный номер этого стикера: {message.sticker.file_id}")


# 4. Запуск двигателя
async def main():
    await dp.start_polling(bot)


# 5. Ключ зажигания
if __name__ == "__main__":
    asyncio.run(main())