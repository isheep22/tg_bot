# ---------------------- 1 - синхронный и асинхронный код

# Синхронный режим (обычный Python):
# Команды выполняются строго по очереди. Пока одна не завершится, вторая не начнется.
# Аналогия: Повар ставит котлету жариться и 5 минут смотрит на нее, ничего не делая.
# Если придет новый клиент — он будет ждать. Ресторан «завис».

# Асинхронный режим (async/await):
# Повар ставит котлету, а пока она жарится — режет булку и принимает заказы.
# Как только котлета готова — он возвращается к ней.
# Результат: бот не зависает и может обрабатывать сотни сообщений одновременно.


# ---------------------- 2 - магические заклинания async и await

# async def — создание «супер-функции».
# Говорит компьютеру: «Эта функция умеет делать паузы и не зависать».
# ВСЕ функции-хэндлеры (ловушки) в боте должны быть async!

# await — команда «Подожди, но не спи».
# Ставится перед действиями, которые занимают время (отправка сообщения).
# Говорит: «Бот, отправь письмо и, пока оно летит, займись другими делами».

# ВАЖНО: Если забыть await перед отправкой сообщения — бот не выдаст ошибку,
# но сообщение просто не уйдет. Это самая частая «баг-ловушка».


# ---------------------- 3 - импортируем магический фильтр F

# Чтобы бот различал, что ему прислали (текст, стикер, фото),
# используем специальный сканер — фильтр F.

from aiogram import F


# ---------------------- 4 - код «Цифрового зеркала»

# Ставим «датчик» на любой входящий текст
@dp.message(F.text)
async def echo_mirror(message: types.Message):
    # Бот берет текст из «конверта» и отправляет его обратно
    await message.answer(message.text)

# Разбор:
# 1. @dp.message(F.text) — сенсор срабатывает ТОЛЬКО на текст.
#    Стикер или фото он проигнорирует.
# 2. async def echo_mirror — асинхронная функция (наш Шеф-повар).
# 3. message.text — содержимое, которое написал пользователь.


# ---------------------- 5 - эксперимент «Answer vs Reply»

# Два способа заставить бота отправить сообщение:

# answer — просто отправляет новое сообщение.
await message.answer(message.text)

# reply — «отвечает» на сообщение, прикрепляя цитату оригинала.
await message.reply(message.text)


# ---------------------- 6 - анатомия объекта Message

# message — это не просто строка, а сложный контейнер («посылка»).
# Внутри него много «отсеков»:
# - text — здесь хранятся только буквы и цифры.
# - photo — здесь лежит информация об изображении.
# - sticker — здесь данные о наклейке.
# - from_user — «паспорт» отправителя (first_name, ID, никнейм).

# ВАЖНО: Имя (first_name) есть у всех, а фамилия или никнейм могут отсутствовать.
# Поэтому для надежности используем именно имя.


# ============================================================
# ТАБЛИЦА КЛАССОВ И МЕТОДОВ:
# ============================================================
# async def            | создание асинхронной функции
# await                | подожди, но не спи (не блокируй программу)
# from aiogram import F| импорт фильтров для распознавания контента
# F.text               | фильтр для текстовых сообщений
# F.sticker            | фильтр для стикеров
# message.text         | текст входящего сообщения
# message.answer()     | отправить ответ
# message.reply()      | ответить с цитатой (reply)
# message.answer_sticker() | отправить стикер обратно
# message.sticker.file_id  | уникальный ID стикера
# message.from_user.first_name | имя пользователя
# len()                | длина строки (количество символов)
# ============================================================

# ============================================================
# КЛЮЧЕВЫЕ МОМЕНТЫ:
# ============================================================
# 1. Асинхронность позволяет боту не зависать на одном пользователе
# 2. async def — метка «супер-функции»
# 3. await — команда «подожди, но не спи»
# 4. F.text — фильтр, ловит только текст
# 5. message.text — обычная строка, с ней работают все методы Python
# 6. answer — просто отправляет, reply — цитирует
# 7. file_id — уникальный адрес файла на серверах Telegram
# 8. Если фильтр не совпадает — хэндлер не срабатывает


