# pip install aiogram


# ---------------------- 4 - импорты и логирование

import asyncio
import logging
from aiogram import Bot, Dispatcher, types
from aiogram.filters.command import Command

# Включаем журнал событий (логирование)
# Будем видеть в терминале, что происходит с ботом
logging.basicConfig(level=logging.INFO)


# ---------------------- 5 - создаём тело и мозг бота

# bot — "тело", выполняет приказы (отправляет сообщения)
# token — энергетическое ядро, без него бот — груда металла
bot = Bot(token="ВСТАВЬ_СЮДА_СВОЙ_ТОКЕН")

# dp — "мозг" (Dispatcher), принимает решения
# Он видит сообщение и решает: какая функция должна сработать
dp = Dispatcher()


# ---------------------- 6 - ставим ловушку (хэндлер)

# @dp.message(Command("start")) — "наклейка" для Диспетчера
# Говорит: "Если прилетит /start — выполняй функцию ниже"

@dp.message(Command("start"))
async def cmd_start(message: types.Message):
    # Бот печатает ответ
    await message.answer("Привет! Я твой первый бот! 😊")


# ---------------------- 7 - запуск двигателя (Polling)

# async def main() — асинхронная функция (турбо-режим)
# start_polling — "радар", бесконечный цикл опроса сервера

async def main():
    await dp.start_polling(bot)


# ---------------------- 8 - красная кнопка старта

# if __name__ == "__main__" — ключ зажигания
# Защищает от случайного запуска, если файл импортируют

if __name__ == "__main__":
    asyncio.run(main())


