# ---------------------- 1 - что такое API и как работают боты

# Бот — это не приложение внутри телефона.
# Бот — это скрипт на Python, который запущен на компьютере (сервере).
#
# Аналогия с рестораном:
# 1. Пользователь — Клиент за столиком.
# 2. Telegram — Официант (передает сообщения).
# 3. Бот (код) — Повар (готовит ответ).

# Polling (опрос) — бот постоянно "стучится" к серверам Telegram:
# "Есть новые сообщения? А сейчас? А сейчас?"


# ---------------------- 2 - регистрация бота через BotFather

# 1. Зайти в Telegram.
# 2. Найти @BotFather (с синей галочкой!).
# 3. Нажать Start.
# 4. Отправить команду /newbot.
# 5. Придумать Имя (Name).
# 6. Придумать Юзернейм (Username), заканчивается на bot.
#
# BotFather выдаст TOKEN — длинный набор букв и цифр.
# Это "паспорт" бота. Его нельзя никому показывать!


# ---------------------- 3 - установка библиотеки

