import asyncio
import logging
from aiogram import Bot, Dispatcher, types, F
from aiogram.filters.command import Command

# 1. Логирование
logging.basicConfig(level=logging.INFO)

# 2. Тело и мозг
bot = Bot(token="ВСТАВЬ_СЮДА_СВОЙ_ТОКЕН")
dp = Dispatcher()


# 3. Ловушки (хэндлеры)
@dp.message(Command("start"))
async def cmd_start(message: types.Message):
    """Реакция на /start — приветствие по имени"""
    await message.answer(
        f"Привет, {message.from_user.first_name}! Я твой первый бот! 😊"
    )


@dp.message(Command("help"))
async def cmd_help(message: types.Message):
    """Реакция на /help — справка"""
    await message.answer(
        "Это бот-помощник. Я пока ничего не умею, но скоро научусь!"
    )


@dp.message(F.text)
async def echo_handler(message: types.Message):
    """Эхо-бот: повторяет любой текст с эмодзи"""
    await message.answer(f"{message.text} 🐱")


# 4. Запуск двигателя
async def main():
    await dp.start_polling(bot)


# 5. Ключ зажигания
if __name__ == "__main__":
    asyncio.run(main())